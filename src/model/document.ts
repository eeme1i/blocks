export type Point = { x: number; y: number };
export type Size = { width: number; height: number };

export const imageParameterNames = [
  "format",
  "width",
  "height",
  "alt",
  "page",
  "fit",
  "scaling",
  "icc",
] as const;
export type ImageParameter = (typeof imageParameterNames)[number];
export const figureParameterNames = [
  "placement",
  "scope",
  "kind",
  "supplement",
  "numbering",
  "gap",
  "outlined",
] as const;
export type FigureParameter = (typeof figureParameterNames)[number];
export type ImageSettings = {
  assetId: string;
  caption: string;
  alt: string;
  width: number;
  source?: string;
  parameters?: Partial<Record<ImageParameter, string>>;
  figure?: boolean;
  label?: string;
  figureParameters?: Partial<Record<FigureParameter, string>>;
};

export type Block = {
  id: string;
  content: string;
  image?: ImageSettings;
  alternatives: Block[];
  position?: Point;
  size?: Size;
};

export type BlocksDocument = {
  version: 1;
  blocks: Block[];
};

const TYPST_HEADER = [
  "// Generated by Blocks. Edit the .blocks document, not this export.",
  "#set page(margin: 1in)",
  '#set text(font: "Libertinus Serif", size: 11pt)',
].join("\n");

